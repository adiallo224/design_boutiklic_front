export type MessageKey = keyof (typeof MESSAGES)['fr']

export function pickLocale(value: string | null | undefined): Locale {
  return isSupportedLocale(value) ? value : DEFAULT_LOCALE
}

export function translate(locale: Locale, key: MessageKey): string {
  return MESSAGES[locale][key] ?? MESSAGES.fr[key]
}

/** Libellé d'un état renvoyé par l'API (« orderStatus_PLACED »...); l'état brut si inconnu (jamais de page cassée pour un état ajouté plus tard). */
export function statusLabel(locale: Locale, prefix: 'orderStatus' | 'fulfillment' | 'payment', status: string): string {
  const key = `${prefix}_${status}` as MessageKey
  return key in MESSAGES.fr ? translate(locale, key) : status
}
